"""Writes the Android vector drawables (launcher, monochrome, Quick Settings tile) from the logo geometry.

py -3 branding/tools/gen_android.py
Geometry matches branding/logo.svg (256-unit canvas): a phone that is a USB stick, with Wi-Fi on its screen.
"""
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RES = os.path.join(ROOT, "android", "app", "src", "main", "res", "drawable")


def rr(x, y, w, h, r):
    return (f"M{x+r},{y}H{x+w-r}A{r},{r} 0 0 1 {x+w},{y+r}V{y+h-r}A{r},{r} 0 0 1 {x+w-r},{y+h}"
            f"H{x+r}A{r},{r} 0 0 1 {x},{y+h-r}V{y+r}A{r},{r} 0 0 1 {x+r},{y}Z")


BODY = rr(78, 34, 100, 150, 22)
SCREEN = rr(91, 48, 74, 112, 11)
PLUG = rr(102, 182, 52, 40, 6)
PINS = rr(112, 194, 11, 11, 2) + rr(133, 194, 11, 11, 2)
WIFI1 = "M100,98 a40,40 0 0 1 56,0"
WIFI2 = "M111,114 a24,24 0 0 1 34,0"
DOT = "M128,124 a7,7 0 1 1 0,14 a7,7 0 1 1 0,-14Z"
W, V = "#FFFFFFFF", "#FF5B21B6"


def grp(s, cx, cy, inner):
    return (f'<group android:translateX="{cx-128*s:.3f}" android:translateY="{cy-128*s:.3f}" '
            f'android:scaleX="{s}" android:scaleY="{s}">\n{inner}\n    </group>')


def vec(dp, vp, body, ns=""):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Phonestick mark: a phone that is a USB stick, with Wi-Fi. Generated by branding/tools/gen_android.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"{ns}
    android:width="{dp}dp" android:height="{dp}dp" android:viewportWidth="{vp}" android:viewportHeight="{vp}">
    {body}
</vector>
'''


def stroke(d):
    return f'        <path android:strokeColor="{W}" android:strokeWidth="10" android:strokeLineCap="round" android:pathData="{d}"/>'


FULL = "\n".join([
    f'        <path android:fillColor="{W}" android:pathData="{BODY}"/>',
    f'        <path android:fillColor="{V}" android:pathData="{SCREEN}"/>',
    stroke(WIFI1), stroke(WIFI2),
    f'        <path android:fillColor="{W}" android:pathData="{DOT}"/>',
    f'        <path android:fillColor="{W}" android:pathData="{PLUG}"/>',
    f'        <path android:fillColor="{V}" android:pathData="{PINS}"/>',
])


def mono(wifi=True):
    parts = [f'        <path android:fillColor="{W}" android:fillType="evenOdd" android:pathData="{BODY}{SCREEN}"/>',
             f'        <path android:fillColor="{W}" android:fillType="evenOdd" android:pathData="{PLUG}{PINS}"/>']
    if wifi:
        parts += [stroke(WIFI1), stroke(WIFI2), f'        <path android:fillColor="{W}" android:pathData="{DOT}"/>']
    return "\n".join(parts)


BG = '''<path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="54" android:startY="0" android:endX="54" android:endY="108">
                <item android:offset="0" android:color="#FF7C3AED"/>
                <item android:offset="1" android:color="#FF5B21B6"/>
            </gradient>
        </aapt:attr>
    </path>'''


def write(name, text):
    with open(os.path.join(RES, name), "w", newline="\n", encoding="utf-8") as f:
        f.write(text)


if __name__ == "__main__":
    write("ic_launcher_fg.xml", vec(108, 108, grp(0.30, 54, 54, FULL)))
    write("ic_launcher_mono.xml", vec(108, 108, grp(0.30, 54, 54, mono())))
    write("ic_launcher_bg.xml", vec(108, 108, BG, ' xmlns:aapt="http://schemas.android.com/aapt"'))
    write("ic_tile_on.xml", vec(24, 24, grp(0.115, 12, 12, mono(True))))
    write("ic_tile_off.xml", vec(24, 24, grp(0.115, 12, 12, mono(False))))
    write("ic_glyph.xml", vec(24, 24, grp(0.115, 12, 12, mono(True))))
    print("ok")
