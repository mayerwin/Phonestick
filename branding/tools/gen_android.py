"""Writes the Android vector drawables (launcher, monochrome, QS tile) from the logo geometry.

py -3 branding/tools/gen_android.py
Geometry is the 64-unit small logo: a phone with a USB plug, tilted -40 degrees, and a signal arc.
"""
import os
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RES = os.path.join(ROOT, "android", "app", "src", "main", "res")

def rr(x, y, w, h, r):
    """Rounded rectangle path, clockwise."""
    return (f"M{x+r},{y}H{x+w-r}A{r},{r} 0 0 1 {x+w},{y+r}V{y+h-r}A{r},{r} 0 0 1 {x+w-r},{y+h}"
            f"H{x+r}A{r},{r} 0 0 1 {x},{y+h-r}V{y+r}A{r},{r} 0 0 1 {x+r},{y}Z")

def rr_ccw(x, y, w, h, r):
    """Rounded rectangle path, counter-clockwise (a hole with nonZero fill)."""
    return (f"M{x+r},{y}A{r},{r} 0 0 0 {x},{y+r}V{y+h-r}A{r},{r} 0 0 0 {x+r},{y+h}H{x+w-r}"
            f"A{r},{r} 0 0 0 {x+w},{y+h-r}V{y+r}A{r},{r} 0 0 0 {x+w-r},{y}Z")

BODY = rr(19, 2, 26, 38, 6)
SCREEN_HOLE = rr_ccw(23.5, 6.5, 17, 29, 2.5)
SCREEN = rr(23.5, 6.5, 17, 29, 2.5)
PLUG = rr(25, 39, 14, 10, 1.5)
WAVE = "M23,55A12,12 0 0 0 41,55"
WAVE2 = "M17,61A20,20 0 0 0 47,61"

def glyph(vp_size, scale, cx, cy, white_only, waves=1, screen_color=None):
    # place the 64-unit glyph (center 32,33) at (cx,cy) with scale
    items = []
    if white_only:
        items.append(f'<path android:fillColor="#FFFFFFFF" android:pathData="{BODY}{SCREEN_HOLE}"/>')
    else:
        items.append(f'<path android:fillColor="#FFFFFFFF" android:pathData="{BODY}"/>')
        items.append(f'<path android:fillColor="{screen_color}" android:pathData="{SCREEN}"/>')
    items.append(f'<path android:fillColor="#FFFFFFFF" android:pathData="{PLUG}"/>')
    if waves >= 1:
        items.append(f'<path android:strokeColor="#FFFFFFFF" android:strokeWidth="5" android:strokeLineCap="round" android:pathData="{WAVE}"/>')
    if waves >= 2:
        items.append(f'<path android:strokeColor="#B3FFFFFF" android:strokeWidth="5" android:strokeLineCap="round" android:pathData="{WAVE2}"/>')
    inner = "\n            ".join(items)
    return (f'<group android:translateX="{cx - 32*scale}" android:translateY="{cy - 33*scale}" '
            f'android:scaleX="{scale}" android:scaleY="{scale}">\n'
            f'        <group android:pivotX="32" android:pivotY="33" android:rotation="-40">\n            {inner}\n        </group>\n    </group>')

def vector(dp, vp, body, extra_ns=""):
    return (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by branding/tools/gen_android.py -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"{extra_ns}\n'
            f'    android:width="{dp}dp" android:height="{dp}dp"\n'
            f'    android:viewportWidth="{vp}" android:viewportHeight="{vp}">\n    {body}\n</vector>\n')

def write(rel, text):
    p = os.path.join(RES, rel); os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, "w", encoding="utf-8", newline="\n").write(text)

AAPT = ' xmlns:aapt="http://schemas.android.com/aapt"'
bg = ('<path android:pathData="M0,0h108v108h-108z">\n        <aapt:attr name="android:fillColor">\n'
      '            <gradient android:type="linear" android:startX="20" android:startY="0" android:endX="88" android:endY="108">\n'
      '                <item android:offset="0" android:color="#FFA855F7"/>\n'
      '                <item android:offset="0.5" android:color="#FF6D28D9"/>\n'
      '                <item android:offset="1" android:color="#FF0891B2"/>\n'
      '            </gradient>\n        </aapt:attr>\n    </path>\n'
      '    <path android:pathData="M0,0h108v108h-108z">\n        <aapt:attr name="android:fillColor">\n'
      '            <gradient android:type="radial" android:centerX="92" android:centerY="98" android:gradientRadius="60">\n'
      '                <item android:offset="0" android:color="#9922D3EE"/>\n'
      '                <item android:offset="1" android:color="#0022D3EE"/>\n'
      '            </gradient>\n        </aapt:attr>\n    </path>')
write("drawable/ic_launcher_bg.xml", vector(108, 108, bg, AAPT))
# Safe zone is the central 66dp circle: glyph ~ 50 units tall rotated, scale 0.82 around center.
write("drawable/ic_launcher_fg.xml", vector(108, 108, glyph(108, 0.86, 54, 54, False, 1, "#FF3B1A8F")))
write("drawable/ic_launcher_mono.xml", vector(108, 108, glyph(108, 0.86, 54, 54, True, 1)))
write("drawable/ic_tile_on.xml", vector(24, 24, glyph(24, 0.36, 12, 12, True, 1)))
write("drawable/ic_tile_off.xml", vector(24, 24, glyph(24, 0.36, 12, 11, True, 0)))
write("drawable/ic_glyph.xml", vector(64, 64, glyph(64, 1.0, 32, 32, True, 2)))
for old in ("drawable/ic_tile.xml",):
    p = os.path.join(RES, old)
    if os.path.exists(p): os.remove(p)
write("mipmap-anydpi/ic_launcher.xml",
      '<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
      '    <background android:drawable="@drawable/ic_launcher_bg" />\n'
      '    <foreground android:drawable="@drawable/ic_launcher_fg" />\n'
      '    <monochrome android:drawable="@drawable/ic_launcher_mono" />\n</adaptive-icon>\n')
print("ok")
